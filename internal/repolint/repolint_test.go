package repolint

import (
	"os"
	"strings"
	"testing"
	"testing/fstest"
)

func TestDetectsComments(t *testing.T) {
	cases := []struct {
		name    string
		path    string
		content string
		want    int
	}{
		{"go line comment", "a.go", "package a\n\n// explains\nfunc F() {}\n", 1},
		{"go doc comment", "a.go", "// Package a does x.\npackage a\n", 1},
		{"go block comment", "a.go", "package a\n\n/* note */\nvar X = 1\n", 1},
		{"go url in string is not a comment", "a.go", "package a\n\nvar U = \"http://x\"\n", 0},
		{"go embed directive", "a.go", "package a\n\nimport \"embed\"\n\n//go:embed x\nvar FS embed.FS\n", 0},
		{"go build directive", "a.go", "//go:build live\n\npackage a\n", 0},
		{"generated go file", "a.go", "// Code generated by sqlc. DO NOT EDIT.\n// versions: x\n\npackage a\n", 0},
		{"sql comment", "q.sql", "-- why\nSELECT 1;\n", 1},
		{"goose annotations", "m.sql", "-- +goose Up\nCREATE TABLE t();\n-- +goose Down\nDROP TABLE t;\n", 0},
		{"sqlc annotation", "q.sql", "-- name: X :one\nSELECT 1;\n", 0},
		{"html comment", "t.html", "<p>x</p>\n<!-- todo -->\n", 1},
		{"template comment", "t.html", "{{/* note */}}\n", 1},
		{"css comment", "a.css", "/* theme */\nbody{}\n", 1},
		{"js line comment", "a.js", "  // note\nlet a = 1;\n", 1},
		{"js url is not a comment", "a.js", "fetch(\"https://x\");\n", 0},
		{"yaml comment", "c.yml", "a: 1\n# note\n", 1},
		{"yaml dollar escape is not a comment", "c.yml", "test: [\"x $${A}\"]\n", 0},
		{"toml comment", "uk.toml", "# note\n[a]\nb = \"c\"\n", 1},
		{"dockerfile comment", "Dockerfile", "# base\nFROM x\n", 1},
		{"gitignore comment", ".gitignore", "# secrets\n.env\n", 1},
		{"env example comment", ".env.example", "# db\nA=1\n", 1},
		{"makefile comment", "Makefile", "# build\nbuild:\n\tgo build\n", 1},
		{"markdown is prose", "README.md", "# Title\n<!-- x -->\n", 0},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := Check(fstest.MapFS{tc.path: {Data: []byte(tc.content)}})
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != tc.want {
				t.Errorf("found %d comments, want %d: %v", len(got), tc.want, got)
			}
		})
	}
}

func TestSkipsGeneratedAndVendoredDirs(t *testing.T) {
	got, err := Check(fstest.MapFS{
		".git/hooks/pre-commit":   {Data: []byte("# hook\n")},
		"internal/db/gen/db.go":   {Data: []byte("// generated\npackage dbgen\n")},
		"node_modules/x/index.js": {Data: []byte("// lib\n")},
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 0 {
		t.Errorf("checked files outside the project's own code: %v", got)
	}
}

func TestRepositoryHasNoComments(t *testing.T) {
	violations, err := Check(os.DirFS("../.."))
	if err != nil {
		t.Fatalf("scan failed, cannot prove the rule holds: %v", err)
	}
	for _, v := range violations {
		t.Errorf("%s:%d: comment found (project rule: no comments in code): %s", v.Path, v.Line, strings.TrimSpace(v.Text))
	}
}
